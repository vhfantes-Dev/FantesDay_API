-- Schema base da FantesDay API (o que o Hibernate criava com ddl-auto=update ate a introducao do Flyway).
-- Em um banco que ja tem essas tabelas, o Flyway marca esta versao como aplicada (baseline-on-migrate)
-- e roda so as migracoes seguintes.

create table users (
    id bigint generated by default as identity,
    name varchar(255) not null,
    email varchar(255) not null unique,
    password_hash varchar(255) not null,
    face_id_enabled boolean,
    bodyweight_kg numeric(5,2),
    sex varchar(255) check (sex in ('MALE','FEMALE')),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table progress (
    user_id bigint not null,
    total_xp integer,
    level integer,
    category varchar(255),
    updated_at timestamp(6) not null,
    primary key (user_id),
    foreign key (user_id) references users
);

create table nutrition_goals (
    user_id bigint not null,
    daily_calories integer,
    proteing numeric(6,2),
    carbsg numeric(6,2),
    fatg numeric(6,2),
    updated_at timestamp(6) not null,
    primary key (user_id),
    foreign key (user_id) references users
);

create table tasks (
    id bigint generated by default as identity,
    user_id bigint not null,
    title varchar(255) not null,
    type varchar(255),
    date date,
    time time(0),
    week_days varchar(255),
    completed boolean,
    completed_at timestamp(6),
    primary key (id),
    foreign key (user_id) references users
);

create table activities (
    id bigint generated by default as identity,
    user_id bigint not null,
    activity_type varchar(255) not null,
    duration_minutes integer,
    origin varchar(255),
    import_source varchar(255),
    calories_burned integer,
    date date,
    primary key (id),
    foreign key (user_id) references users
);

create table foods (
    id bigint generated by default as identity,
    name varchar(255) not null,
    calories_per_100g numeric(7,2),
    protein_per_100g numeric(7,2),
    carbs_per_100g numeric(7,2),
    fat_per_100g numeric(7,2),
    fiber_per_100g numeric(7,2),
    default_unit varchar(255),
    source varchar(255) check (source in ('TACO','OPEN_FOOD_FACTS','FREE_EXERCISE_DB','CUSTOM')),
    external_id varchar(255),
    primary key (id),
    unique (source, external_id)
);

create table meals (
    id bigint generated by default as identity,
    user_id bigint not null,
    name varchar(255),
    date date,
    created_at timestamp(6) not null,
    primary key (id),
    foreign key (user_id) references users
);

create table meal_items (
    id bigint generated by default as identity,
    meal_id bigint not null,
    food_id bigint not null,
    quantity numeric(8,2),
    unit varchar(255),
    calculated_calories integer,
    calculated_protein numeric(8,2),
    calculated_carbs numeric(8,2),
    calculated_fat numeric(8,2),
    primary key (id),
    foreign key (meal_id) references meals,
    foreign key (food_id) references foods
);

create table exercises (
    id bigint generated by default as identity,
    name varchar(255) not null,
    muscle_group varchar(255),
    secondary_muscles varchar(255),
    equipment varchar(255),
    level varchar(255),
    category varchar(255),
    instructions text,
    image_url varchar(255),
    source varchar(255) check (source in ('TACO','OPEN_FOOD_FACTS','FREE_EXERCISE_DB','CUSTOM')),
    external_id varchar(255) unique,
    primary key (id)
);

create table workouts (
    id bigint generated by default as identity,
    user_id bigint not null,
    workout_type varchar(255),
    date date,
    xp_earned integer,
    primary key (id),
    foreign key (user_id) references users
);

create table workout_exercises (
    id bigint generated by default as identity,
    workout_id bigint not null,
    exercise_id bigint not null,
    primary key (id),
    foreign key (workout_id) references workouts,
    foreign key (exercise_id) references exercises
);

create table workout_sets (
    id bigint generated by default as identity,
    workout_exercise_id bigint not null,
    reps integer not null,
    weight_kg numeric(6,2),
    estimated_one_rep_max numeric(7,2),
    personal_record boolean,
    created_at timestamp(6) not null,
    primary key (id),
    foreign key (workout_exercise_id) references workout_exercises
);
