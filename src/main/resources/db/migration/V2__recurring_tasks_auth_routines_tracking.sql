-- ---------- Tarefas recorrentes: uma conclusao por dia ----------
create table task_completions (
    id bigint generated by default as identity,
    task_id bigint not null references tasks,
    date date not null,
    xp_earned integer,
    completed_at timestamp(6) not null,
    primary key (id),
    unique (task_id, date)
);

-- Conclusoes antigas (campo tasks.completed) viram registros em task_completions.
-- xp_earned = 0 porque nao da para saber se elas deram XP; desmarcar nao vai descontar nada.
insert into task_completions (task_id, date, xp_earned, completed_at)
select id, coalesce(date, cast(completed_at as date)), 0, completed_at
from tasks
where completed = true and completed_at is not null;

alter table tasks drop column completed;
alter table tasks drop column completed_at;

-- ---------- Atividades: XP e importacao (Apple Saude, Google Fit...) ----------
alter table activities add column xp_earned integer;
alter table activities add column external_id varchar(255);
alter table activities add constraint uk_activities_import unique (user_id, import_source, external_id);

-- ---------- Catalogo: dono dos itens cadastrados manualmente ----------
alter table foods add column created_by_id bigint references users;
alter table exercises add column created_by_id bigint references users;

-- ---------- Metas: nomes de coluna corrigidos e meta de agua ----------
alter table nutrition_goals rename column proteing to protein_g;
alter table nutrition_goals rename column carbsg to carbs_g;
alter table nutrition_goals rename column fatg to fat_g;
alter table nutrition_goals add column daily_water_ml integer;

-- ---------- Autenticacao: refresh token e recuperacao de senha ----------
create table refresh_tokens (
    id bigint generated by default as identity,
    user_id bigint not null references users,
    token_hash varchar(64) not null unique,
    expires_at timestamp(6) with time zone not null,
    revoked_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    primary key (id)
);

create table password_reset_codes (
    id bigint generated by default as identity,
    user_id bigint not null references users,
    code_hash varchar(64) not null,
    expires_at timestamp(6) with time zone not null,
    attempts integer,
    used_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    primary key (id)
);

-- ---------- Rotinas de treino ----------
create table workout_routines (
    id bigint generated by default as identity,
    user_id bigint not null references users,
    name varchar(255) not null,
    notes text,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table routine_exercises (
    id bigint generated by default as identity,
    routine_id bigint not null references workout_routines,
    exercise_id bigint not null references exercises,
    position integer not null,
    target_sets integer,
    target_reps varchar(255),
    rest_seconds integer,
    primary key (id)
);

-- ---------- Agua, peso e foto de perfil ----------
create table water_entries (
    id bigint generated by default as identity,
    user_id bigint not null references users,
    date date not null,
    amount_ml integer not null,
    created_at timestamp(6) not null,
    primary key (id)
);

create table weight_entries (
    id bigint generated by default as identity,
    user_id bigint not null references users,
    date date not null,
    weight_kg numeric(5,2) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    unique (user_id, date)
);

create table user_photos (
    user_id bigint not null references users,
    data bytea not null,
    content_type varchar(255) not null,
    updated_at timestamp(6) not null,
    primary key (user_id)
);

alter table users add column photo_updated_at timestamp(6);

-- ---------- Limpeza: colunas que deixaram de ser usadas quando as series viraram WorkoutSet ----------
alter table workout_exercises drop column if exists sets;
alter table workout_exercises drop column if exists reps;
alter table workout_exercises drop column if exists weight_kg;

-- ---------- Indices para as consultas por usuario/data ----------
create index if not exists idx_tasks_user on tasks (user_id);
create index if not exists idx_activities_user_date on activities (user_id, date);
create index if not exists idx_meals_user_date on meals (user_id, date);
create index if not exists idx_workouts_user_date on workouts (user_id, date);
create index if not exists idx_water_entries_user_date on water_entries (user_id, date);
create index if not exists idx_refresh_tokens_user on refresh_tokens (user_id);
create index if not exists idx_password_reset_codes_user on password_reset_codes (user_id);
create index if not exists idx_routine_exercises_routine on routine_exercises (routine_id);
